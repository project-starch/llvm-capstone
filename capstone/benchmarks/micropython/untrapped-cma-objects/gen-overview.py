#!/usr/bin/env python3
"""Generate the overview of defects on CUSTOM-ALLOCATOR OBJECTS that Capstone does
not trap. Generated, not hand-written, because a hand-written subset drifts from the
corpora it summarises -- MPY-T16's README claimed "NOT REPRODUCIBLE HERE" for weeks
after it had been measured, and nothing checked it against the row it described.

    python3 gen-overview.py            rewrite README.md and overview.csv
    python3 gen-overview.py --check    exit 1 if either is out of date

THE SELECTION IS A QUERY, NOT A LIST:

    domain_behaviour starts with "untrapped"   AND   scope is a GC-heap scope

Both halves are load-bearing. Dropping the first would pull in the three cause-24
faults, which trap for a reason that has nothing to do with lifetime -- a NULL or
uninitialised word used as a pointer, which is a TAG check. Dropping the second
would pull in MPY-S31, which is untrapped but lives on the C STACK: that object does
carry its own capability, and the access simply fitted inside it. Including it would
turn a sharp claim into a vague one.
"""
import csv, os, sys

S = os.path.dirname(os.path.abspath(__file__))
MPY = os.path.dirname(S)
GC_SCOPES = {"gc-managed", "gc-core", "gc-heap"}
SRC = [("temporal", f"{MPY}/temporal-corpus/temporal-allocator-corpus.csv", "temporal-corpus"),
       ("spatial",  f"{MPY}/spatial-corpus/spatial-allocator-corpus.csv",   "spatial-corpus")]

def collect():
    out = []
    for kind, path, base in SRC:
        for r in csv.DictReader(open(path)):
            if r["domain_behaviour"].startswith("untrapped") and r["scope"] in GC_SCOPES:
                d = None
                for sub in ("cases", "excluded-cases"):
                    p = f"{MPY}/{base}/{sub}"
                    if os.path.isdir(p):
                        for name in os.listdir(p):
                            if name.startswith(r["id"] + "_"):
                                d = f"{base}/{sub}/{name}"
                r["_kind"], r["_dir"] = kind, d
                out.append(r)
    return sorted(out, key=lambda r: (r["_kind"], r["id"]))

STRENGTH = {
    "untrapped-identical":  "corruption verified",
    "untrapped-no-crash":   "no crash, corruption not shown",
}

def render(rows):
    L = []
    A = L.append
    A("# Defects on custom-allocator objects that Capstone does not trap\n")
    A("**Generated by `gen-overview.py` from the two corpora. Do not edit by hand.**")
    A("Run `python3 gen-overview.py --check` to detect drift.\n")
    A(f"{len(rows)} measured rows. Every one is a real defect, executed in a")
    A("pure-capability domain on an UNMODIFIED MicroPython, and the hardware did not")
    A("object. This is the set the whole nested-allocator finding rests on.\n")
    A("## The rows\n")
    A("| case | upstream | class | component | stock | in the domain | reproduce |")
    A("|---|---|---|---|---|---|---|")
    for r in rows:
        link = f"[`run.sh`](../{r['_dir']}/run.sh)" if r["_dir"] else "—"
        A(f"| `{r['id']}` | {r['ref']} | {r['class']} | `{r['component']}` | "
          f"{r['stock_behaviour']} | {STRENGTH.get(r['domain_behaviour'], r['domain_behaviour'])} | {link} |")
    A("")
    A("`stock` is what an ordinary host MicroPython does with the same input.")
    A("Note how often it is `silent-no-effect`: most of these defects are invisible")
    A("without a sanitizer even before capability hardware is involved.\n")
    A("## Why these and not the others\n")
    A("The selection is a query over the corpora, not a curated list:\n")
    A("    domain_behaviour starts with \"untrapped\"  AND  scope is a GC-heap scope\n")
    A("Two kinds of row are deliberately OUT, and both exclusions carry a finding:\n")
    A("- **The three `cause 24` faults** (`MPY-T11`, `MPY-T12`, `MPY-T25`) are trapped,")
    A("  but not for a lifetime reason. `cause 24` is a TAG check: it fires when a word")
    A("  that is not a capability is used as a pointer. `T12` dereferences a NULL,")
    A("  `T25` uninitialised state — and `T25` is not even a temporal defect, which is")
    A("  the proof that this code says nothing about lifetimes. A stale pointer into a")
    A("  freed GC block is a perfectly valid tagged capability and never produces it.")
    A("  `T11` and `T12` fault at the SAME pc, `0x101619b00`.")
    A("- **`MPY-S31`** is untrapped but lives on the C stack, which does carry its own")
    A("  capability; the access simply fitted inside it. Including it would blur the")
    A("  claim from \"the allocator's objects are invisible\" into \"nothing traps\".\n")
    A("## The mechanism, measured three ways\n")
    A("| the object comes from | bounds the hardware reported | outcome |")
    A("|---|---|---|")
    A("| MicroPython's `m_new` | `0x60000` = 384 KiB = the whole heap | untrapped |")
    A("| a model bump allocator | `0x400` = 1 KiB = the whole region | untrapped |")
    A("| the linker, a plain global | `0x40` = **64 B = the object itself** | **trapped** |")
    A("")
    A("Same source shape, same flags, same domain; the only variable is whether the")
    A("object was carved by an allocator or assigned by the linker. The hardware bounds")
    A("an object to the byte when it is told what the object is, and bounds the whole")
    A("region when software carves inside it, because no bounds-setting instruction is")
    A("emitted for a sub-allocation. Pairs:")
    A("`../../tests/runtime-qemu/silicon-ladder/run-nested-allocator-pairs.sh`\n")
    A("## Running them\n")
    A("    ./run-all.sh          every row above, control first, verdict per row\n")
    A("Each `run.sh` rebuilds its image, runs its control, and compares what it")
    A("measures against what that case's `RESULT.txt` records. A run whose control")
    A("fails exits 75 with NO verdict rather than reporting a result.\n")
    return "\n".join(L) + "\n"

def main():
    rows = collect()
    md = render(rows)
    cols = ["id", "ref", "class", "cwe", "component", "scope",
            "stock_behaviour", "domain_behaviour", "repro_dir"]
    lines = [",".join(cols)]
    for r in rows:
        lines.append(",".join('"%s"' % (r.get(c) if c != "repro_dir" else (r["_dir"] or "")) for c in cols))
    csv_text = "\n".join(lines) + "\n"

    if "--check" in sys.argv:
        bad = 0
        for name, want in (("README.md", md), ("overview.csv", csv_text)):
            p = os.path.join(S, name)
            got = open(p).read() if os.path.exists(p) else ""
            if got != want:
                print(f"OUT OF DATE: {name}"); bad = 1
        if not bad:
            print(f"up to date: {len(rows)} rows")
        return bad

    open(os.path.join(S, "README.md"), "w").write(md)
    open(os.path.join(S, "overview.csv"), "w").write(csv_text)
    print(f"wrote README.md and overview.csv: {len(rows)} rows")
    for r in rows:
        print(f"   {r['id']:8} {r['ref']:16} {r['scope']:12} {r['domain_behaviour']}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
