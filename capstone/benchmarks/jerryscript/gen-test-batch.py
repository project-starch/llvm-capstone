#!/usr/bin/env python3
"""Turn a slice of JerryScript's own test suite into a C batch the domain can run.

    gen-test-batch.py <jerryscript-src> <first> <count> <out.inc> [group]

GROUP selects which part of the suite, and the default is not an accident:

    (default)   tests/jerry/*.js        1017 files, expected to RUN CLEAN
    fail        tests/jerry/fail/       107 files, expected to THROW -- inverted
                                        expectations, so mixing them into the
                                        default set would corrupt the pass rate
    es.next     tests/jerry/es.next/    18 files, newer language features

The top level is taken WITHOUT recursing, deliberately. `find` counts 1142 .js in
the tree and this takes 1017; the difference is those two groups, and they are
named here rather than left as an 11% silent omission.

The suite is 1142 files and 2.09 MB of source; the domain's code region is 4 MiB
and the interpreter already occupies 2.97 MB of it, so the tests CANNOT all be
embedded at once. They go in slices, and the slice bounds are arguments rather
than a constant so a failing test can be re-run alone without editing anything.

Refuses rather than truncates. A batch that silently drops its tail would report
a pass rate over a set nobody chose -- the same shape as a counter that returns 0
on input it cannot parse, which this project has been burned by.
"""
import os, sys

# Byte budget for the embedded sources. 256 KiB keeps a slice well inside what is
# left of the code region, measured rather than guessed: the interpreter is
# 2,965,696 bytes and the region is 4,194,304.
BUDGET = 256 * 1024


def c_string(data: bytes) -> str:
    out = []
    for b in data:
        if b == 0x22:   out.append('\\"')
        elif b == 0x5C: out.append('\\\\')
        elif b == 0x0A: out.append('\\n')
        elif b == 0x0D: out.append('\\r')
        elif b == 0x09: out.append('\\t')
        elif 0x20 <= b < 0x7F: out.append(chr(b))
        else: out.append('\\%03o' % b)          # octal: no "\x41f" ambiguity
    return ''.join(out)


def main():
    if len(sys.argv) not in (5, 6):
        sys.exit(__doc__)
    src, first, count, out = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
    group = sys.argv[5] if len(sys.argv) > 5 else ''
    if group and group not in ('fail', 'es.next'):
        sys.exit(f"gen-test-batch: unknown group {group!r}; use 'fail' or 'es.next'")
    root = os.path.join(src, 'tests', 'jerry', group)
    if not os.path.isdir(root):
        sys.exit(f"gen-test-batch: no such suite: {root}")

    files = sorted(f for f in os.listdir(root) if f.endswith('.js'))
    if not files:
        sys.exit(f"gen-test-batch: {root} holds no .js files")
    if first >= len(files):
        sys.exit(f"gen-test-batch: first={first} but the suite has {len(files)} files")
    sl = files[first:first + count]

    total = sum(os.path.getsize(os.path.join(root, f)) for f in sl)
    if total > BUDGET:
        sys.exit(f"gen-test-batch: slice [{first},{first+len(sl)}) is {total} bytes, "
                 f"over the {BUDGET} budget. Ask for fewer tests -- this will not "
                 f"quietly ship a shorter batch than you asked for.")

    with open(out, 'w') as fh:
        fh.write(f"/* generated by gen-test-batch.py -- {group or 'tests/jerry (top level)'}, "
                 f"[{first}, {first+len(sl)}) of {len(files)}, {total} bytes.\n"
                 f"   Expectation: {'THROW' if group == 'fail' else 'RUN CLEAN'} */\n")
        fh.write(f"#define JT_EXPECT_THROW {1 if group == 'fail' else 0}\n")
        fh.write(f"#define JT_FIRST {first}\n#define JT_N {len(sl)}\n")
        fh.write("static const char *const jt_name[JT_N] = {\n")
        for f in sl:
            fh.write(f'  "{f}",\n')
        fh.write("};\nstatic const char *const jt_src[JT_N] = {\n")
        for f in sl:
            with open(os.path.join(root, f), 'rb') as g:
                fh.write(f'  "{c_string(g.read())}",\n')
        fh.write("};\n")
    print(f"{len(sl)} tests, {total} bytes -> {out}")


if __name__ == '__main__':
    sys.exit(main())
