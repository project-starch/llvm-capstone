#!/usr/bin/env bash
# Turn a Ruby specimen into port/md_specimen.h, a C array of mruby bytecode.
#
#     tools/gen-specimen.sh cases/a1-6339.rb
#
# The domain has no parser: the gembox is default-no-stdio, so mruby-compiler is
# not in the image and there is no file system to read from either. Bytecode is
# produced here, on the host, by mruby's own mrbc, and embedded. That is not a
# limitation to work around -- it keeps the image to the VM and the GC, which is
# all the study measures, and it means the specimen cannot accidentally exercise
# the parser instead of the collector.
#
# mrbc must come from the SAME tree and the SAME config as the amalgamation. A
# bytecode file carries no record of the object model it was built against, so a
# host mrbc from a different checkout would load and misbehave rather than fail,
# which is the expensive kind of wrong.
set -euo pipefail
SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
PORT_DIR=$(cd -- "$SCRIPT_DIR/../port" && pwd)
source "$SCRIPT_DIR/../../../tests/capstone-test-env.sh"

SRC=${MRUBY_SRC_DIR:-$CAPSTONE_TMP_ROOT/mruby-src}
MRBC="$SRC/build/host/mrbc/bin/mrbc"
RB=${1:?usage: gen-specimen.sh <specimen.rb>}

[[ -x "$MRBC" ]] || { echo "no mrbc at $MRBC -- run the rake amalgam step first" >&2; exit 2; }
[[ -f "$RB" ]] || { echo "no such specimen: $RB" >&2; exit 2; }

OUT="$PORT_DIR/md_specimen.h"
TMP=$(mktemp); trap 'rm -f "$TMP"' EXIT

"$MRBC" -B md_specimen -o "$TMP" "$RB"

{
  echo "/* GENERATED by tools/gen-specimen.sh from $(basename "$RB") -- do not edit."
  echo " *"
  echo " * mruby bytecode, compiled on the host by the mrbc from the same tree and the"
  echo " * same config as the amalgamation. Bytecode carries no record of the object"
  echo " * model it was built against, so a mismatched mrbc would load and misbehave"
  echo " * rather than fail."
  echo " */"
  echo "#ifndef CAPSTONE_MD_SPECIMEN_H"
  echo "#define CAPSTONE_MD_SPECIMEN_H"
  cat "$TMP"
  echo "#endif"
} > "$OUT"

echo "  $(basename "$RB") -> $OUT ($(wc -c < "$TMP") bytes of C)"

# A specimen that compiles to nothing would run cleanly and prove nothing, which is
# the failure this project keeps paying for. Refuse it here rather than let a boot
# discover it.
if ! grep -q "0x52,0x49,0x54,0x45" "$OUT"; then
  echo "no RITE header in the generated bytecode -- mrbc produced nothing usable" >&2
  exit 1
fi
