#!/usr/bin/env python3
"""Emit ONE translation unit: the allocator, rake's mruby.c, and this port.

The gp-captable ABI is why this exists rather than a list of objects.
`getGpCaptableIndex` numbers globals PER MODULE and only one descriptor survives
the link, so separate objects each start their numbering at zero and collide. The
image still links and still reports a cap table, which is what makes the failure
expensive: it builds, and it cannot work.

mruby makes this easy compared with WAMR -- `rake amalgam` already produces a
single mruby.c, so this only has to staple the port onto it. It is still a
generator rather than a hand-written file so that adding a port source cannot be
forgotten.

Order matters in one place: mruby.c comes FIRST, because the port's own code calls
into it and includes mruby.h through it.

    python3 tools/gen-amalgam.py <amalgam-dir> <port-dir> <out.c> [extra.c ...]
"""
import pathlib, sys


def main(argv):
    if len(argv) < 4:
        sys.exit(__doc__)
    amalgam_dir, port_dir, out = pathlib.Path(argv[1]), pathlib.Path(argv[2]), pathlib.Path(argv[3])
    extras = [pathlib.Path(a) for a in argv[4:]]

    mruby_c = amalgam_dir / "mruby.c"
    if not mruby_c.is_file():
        sys.exit(f"no mruby.c at {mruby_c} -- run the rake amalgam step first")

    # Sorted so the unit is reproducible; a build that differs run to run cannot be
    # compared against itself, which is the whole basis of a matched pair.
    port = sorted(p for p in port_dir.glob("*.c"))
    if not port:
        sys.exit(f"no .c files in {port_dir}")

    # ORDER IS LOAD-BEARING and cost a build to find. mruby.c contains
    #     #define malloc(s) mrb_basic_alloc_func(NULL, (s))
    # so anything defining its own malloc must come BEFORE it, or that macro
    # rewrites the definition into a call and the file no longer parses. The
    # extras -- the allocator and libm -- therefore lead; mruby.c follows; the port
    # comes last and reaches mruby through the separate amalgamated mruby.h rather
    # than through mruby.c, which is why it does not need to precede it.
    parts = extras + [mruby_c] + port
    missing = [p for p in parts if not p.is_file()]
    if missing:
        sys.exit("missing: " + ", ".join(str(m) for m in missing))

    lines = [
        "/* GENERATED by tools/gen-amalgam.py -- do not edit.",
        " *",
        " * One translation unit, because the gp-captable ABI numbers globals per",
        " * module and separate objects collide at index zero.",
        " */",
    ]
    lines += ['#include "%s"' % p.resolve() for p in parts]
    out.write_text("\n".join(lines) + "\n")

    print(f"  {len(parts)} sources -> {out}")
    for p in parts:
        print(f"    {p.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
