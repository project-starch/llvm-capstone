#!/usr/bin/env python3
"""Generate port/wamr_test_module.h: a minimal WebAssembly module, hand-encoded.

Hand-encoded rather than produced by wat2wasm so the tree carries no opaque binary
and every byte is accounted for in source. Run from anywhere:

    python3 tools/gen-test-module.py [--a N] [--b N]

--a/--b change the two summands. That is the positive control for a domain that
reports a number: if the reported value does not TRACK the operands, the number
did not come from the interpreter and proves nothing.

Self-check: --verify re-parses the bytes it just emitted and asserts the section
ids, the export name and the opcode sequence. A generator whose output is only
ever read by a machine needs one.
"""
import pathlib, sys

def u32(n):
    out = bytearray()
    while True:
        b = n & 0x7F; n >>= 7
        out.append(b | (0x80 if n else 0))
        if not n:
            return bytes(out)

def s32(n):
    """Signed LEB128, which is what i32.const takes -- NOT the unsigned u32 above.
    Writing the operand as a raw byte silently reinterprets anything over 63 as a
    negative number: 88 became -40, and the domain dutifully returned 11 + -40.
    That reading was correct and the module was wrong."""
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        done = (n == 0 and not b & 0x40) or (n == -1 and b & 0x40)
        out.append(b if done else b | 0x80)
        if done:
            return bytes(out)

def section(sid, body):
    return bytes([sid]) + u32(len(body)) + body

def build(a=7, b=35):
    types = section(1, u32(1) + b"\x60" + u32(0) + u32(1) + b"\x7f")   # () -> i32
    funcs = section(3, u32(1) + u32(0))
    name = b"run"
    exports = section(7, u32(1) + u32(len(name)) + name + b"\x00" + u32(0))
    # i32.const a ; i32.const b ; i32.add ; end
    body = u32(0) + b"\x41" + s32(a) + b"\x41" + s32(b) + b"\x6a" + b"\x0b"
    code = section(10, u32(1) + u32(len(body)) + body)
    return b"\x00asm\x01\x00\x00\x00" + types + funcs + exports + code

def verify(mod, a=7, b=35):
    assert mod[:8] == b"\x00asm\x01\x00\x00\x00", "magic/version"
    ids, i = [], 8
    while i < len(mod):
        sid = mod[i]; i += 1
        n = 0; shift = 0
        while True:
            byte = mod[i]; i += 1   # not `b`: that is a parameter here
            n |= (byte & 0x7F) << shift; shift += 7
            if not (byte & 0x80):
                break
        ids.append(sid); i += n
    assert ids == [1, 3, 7, 10], f"section ids {ids}"
    assert b"run" in mod, "export name"
    want = b"\x41" + s32(a) + b"\x41" + s32(b) + b"\x6a\x0b"
    assert want in mod, f"i32.const {a}, i32.const {b}, i32.add, end"
    return True

HEAD = '''/* A minimal WebAssembly module, hand-encoded so every byte is accounted for
 * in source and the tree carries no opaque binary.
 *
 *   (module (func (result i32) i32.const %d  i32.const %d  i32.add)
 *           (export "run" (func 0)))
 *
 * It ADDS rather than returning a constant on purpose: a constant would pass even
 * if the interpreter never executed an instruction, and this project has paid for
 * that class of test more than once. %d + %d = %d requires the opcode loop to run.
 *
 * GENERATED by tools/gen-test-module.py -- do not edit.
 */
#ifndef CAPSTONE_WAMR_TEST_MODULE_H
#define CAPSTONE_WAMR_TEST_MODULE_H

#define WAMR_TEST_MODULE_EXPECTED %d

static unsigned char wamr_test_module[] = {
'''

def arg(flag, dflt):
    if flag in sys.argv:
        v = int(sys.argv[sys.argv.index(flag) + 1])
        if not -2**31 <= v < 2**31:
            sys.exit(f"{flag} must fit in an i32, got {v}")
        return v
    return dflt

if __name__ == "__main__":
    a, b = arg("--a", 7), arg("--b", 35)
    mod = build(a, b)
    verify(mod, a, b)
    if "--verify" in sys.argv:
        print(f"ok: {len(mod)} bytes, sections 1/3/7/10, export \"run\", {a}+{b}={a+b}")
        sys.exit(0)
    out = pathlib.Path(__file__).resolve().parent.parent / "port" / "wamr_test_module.h"
    rows = "\n".join("    " + ", ".join(f"0x{b:02x}" for b in mod[i:i + 12]) + ","
                     for i in range(0, len(mod), 12))
    out.write_text(HEAD % (a, b, a, b, a + b, a + b) + rows + "\n};\n\n#endif\n")
    print(f"  {len(mod)} bytes -> {out}")
