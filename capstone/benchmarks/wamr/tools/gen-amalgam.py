#!/usr/bin/env python3
"""Concatenate the WAMR core and this port into ONE translation unit.

One TU is a requirement of the gp-captable ABI, not a preference:
getGpCaptableIndex numbers globals per module, so separate objects each start at
zero and collide. Built separately the image links, reports one global in its cap
table and cannot work.

Concatenating collides on file-local statics that share a name. This renames them
PER FILE, which is safe precisely because they are static: nothing outside the
file can refer to them. A symbol that is EXTERN in one file keeps its name there,
because other files call it.

    python3 tools/gen-amalgam.py <wamr-src> <port-dir> <out.c>
"""
import pathlib, re, sys

# Names defined more than once across the sources below. Discovered from the
# compiler's own "redefinition of" / "static declaration of" errors rather than by
# reading, so the list cannot quietly go stale in the other direction: a new
# collision is a build error, not a silent miscompile.
COLLIDING = ["read_leb", "set_error_buf", "set_error_buf_v", "runtime_malloc"]

# File-scope static VARIABLES that share a name. Separate from the list above
# because they are declared "} __ue = ...", so a function-shaped pattern misses
# them entirely -- which it did, and the build said so.
COLLIDING_VARS = ["__ue"]

SKIP = {"wasm_interp_fast.c", "wasm_mini_loader.c"}

def sources(src, port):
    out = []
    for d in ("core/shared/mem-alloc", "core/shared/mem-alloc/ems",
              "core/shared/utils", "core/iwasm/common", "core/iwasm/interpreter"):
        out += sorted((src / d).glob("*.c"))
    # beebs_softfloat_libm.c is IN the amalgamation because it owns two file-scope
    # constants and only one TU may own globals under this ABI.
    out += [pathlib.Path(sys.argv[4])] if len(sys.argv) > 4 else []
    out += [port / "capstone_platform.c", port / "capstone_libc_extra.c",
            port / "wamr_domain.c"]
    return [f for f in out if f.name not in SKIP]

def is_static(text, name):
    """Is `name` defined as a file-local static here? Only those may be renamed.

    The pattern spans a newline on purpose: WAMR writes the return type and the
    name on separate lines, and a same-line regex matched nothing at all -- which
    looked like "no collisions" rather than "the check is broken"."""
    return re.search(r"^static\s[\w \*]*[\s\*]" + re.escape(name) + r"\s*\(",
                     text, re.M) is not None

def is_static_var(text, name):
    """A file-scope static VARIABLE, e.g. `static union { ... } __ue = { ... };`.
    Matched on the name followed by `=` or `;` at file scope rather than on the
    `static` keyword, because the two can be many lines apart."""
    return re.search(r"^\}\s*" + re.escape(name) + r"\s*[=;]", text, re.M) is not None \
        or re.search(r"^static\s[\w \*]*[\s\*]" + re.escape(name) + r"\s*[=;\[]", text, re.M) is not None


def main():
    src, port, out = (pathlib.Path(a) for a in sys.argv[1:4])
    lines = ["/* GENERATED by tools/gen-amalgam.py -- do not edit. */",
             "#include <stdarg.h>"]
    renamed = 0
    for f in sources(src, port):
        text = f.read_text(errors="replace")
        local = [n for n in COLLIDING if is_static(text, n)]
        local += [n for n in COLLIDING_VARS if is_static_var(text, n)]
        tag = f.stem.replace("-", "_")
        for n in local:
            lines.append(f"#define {n} {n}__{tag}")
        lines.append(f'#include "{f}"')
        for n in local:
            lines.append(f"#undef {n}")
        renamed += len(local)
    out.write_text("\n".join(lines) + "\n")
    n = sum(1 for l in lines if l.startswith("#include \""))
    print(f"   {n} sources, {renamed} file-local statics renamed")

if __name__ == "__main__":
    main()
