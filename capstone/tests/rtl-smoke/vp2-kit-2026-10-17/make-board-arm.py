#!/usr/bin/env python3
"""make-board-arm.py <run.py> <out dir> [stage dir on the board, default /test-domains/vm]

vp2's Tier 2 board arm, generated from run.py's own guest SCRIPT so the board runs exactly the steps the QEMU
prediction ran (vp2-kit README, "The board run"). Writes:
  <out>/vm-suite-inner.sh   run.py's SCRIPT, with its stage directory /mnt/vm replaced by the board's
  <out>/vm-suite.sh         the stage-driver arm: runs the inner script, then prints BASELINE-PROBE vm_steps = <n>,
                            the form run_sqlite_stages_fpga.py accepts for a host-binary arm (n = VM_EXIT lines)
  <out>/steps.txt           the VM_EXIT step names in script order, for the comparison against the QEMU record
Exit 2 if run.py has no SCRIPT or the stage path does not occur exactly where expected.
"""
import ast, re, sys, os

if len(sys.argv) < 3: sys.exit(__doc__)
src = open(sys.argv[1]).read(); out = sys.argv[2]; stage = sys.argv[3] if len(sys.argv) > 3 else '/test-domains/vm'
tree = ast.parse(src)
script = next((n.value.value for n in tree.body if isinstance(n, ast.Assign)
               and any(getattr(t, 'id', None) == 'SCRIPT' for t in n.targets)), None)
if not script: print('NO DATA: no SCRIPT assignment in ' + sys.argv[1]); sys.exit(2)
# the stage directory appears as `cd /mnt/vm` and in the perl smoke copy; every occurrence is the staging root
n = script.count('/mnt/vm')
if n < 1 or 'cd /mnt/vm || exit 1' not in script:
    print(f'NO DATA: run.py SCRIPT does not cd into /mnt/vm ({n} occurrences)'); sys.exit(2)
inner = script.replace('/mnt/vm', stage)
steps = []
for m in re.finditer(r'echo VM_EXIT:([^:]+):', inner):
    name = m.group(1)
    if name == '$mode':
        loop = re.search(r'for mode in ([^;]+); do', inner)
        steps += loop.group(1).split()
    else:
        steps.append(name)
os.makedirs(out, exist_ok=True)
open(os.path.join(out, 'vm-suite-inner.sh'), 'w').write(inner)
open(os.path.join(out, 'vm-suite.sh'), 'w').write(f'''#!/bin/sh
# vp2 Tier 2 board arm, generated by make-board-arm.py from {os.path.basename(sys.argv[1])} (sha256 of the SCRIPT text
# below is in steps.txt). The driver needs a BASELINE-PROBE line from a host-binary arm.
sh {stage}/vm-suite-inner.sh > /tmp/vm-suite.out 2>&1
cat /tmp/vm-suite.out
n=0; while read -r l; do case "$l" in VM_EXIT:*) n=$((n+1));; esac; done < /tmp/vm-suite.out
echo "BASELINE-PROBE vm_steps = $n"
''')
import hashlib
open(os.path.join(out, 'steps.txt'), 'w').write(
    f'# SCRIPT sha256 {hashlib.sha256(script.encode()).hexdigest()} from {sys.argv[1]}\n' + '\n'.join(steps) + '\n')
print(f'{len(steps)} steps ({steps[0]} .. {steps[-1]}); stage {stage}; written to {out}')
