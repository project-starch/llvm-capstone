# zbb-arm.S generator + expected values: every Zbb/Zba-profile op the compiler lane's SDK would emit, over edge operands.
import itertools
M=(1<<64)-1
def s64(x): x&=M; return x-(1<<64) if x>>63 else x
def sx32(x): x&=0xffffffff; return (x|~0xffffffff)&M if x>>31 else x
def clz(x,w): x&=(1<<w)-1; return w-x.bit_length()
def ctz(x,w): x&=(1<<w)-1; return w if x==0 else (x&-x).bit_length()-1
def rol(x,s,w): s%=w; x&=(1<<w)-1; return ((x<<s)|(x>>(w-s)))&((1<<w)-1)
def ror(x,s,w): return rol(x,(w-s)%w,w)
OPS={ # name: (kind, fn)  kind r = rd,rs1,rs2 ; u = rd,rs1 ; i = rd,rs1,imm
 'andn':('r',lambda a,b:a&~b&M),'orn':('r',lambda a,b:(a|~b)&M),'xnor':('r',lambda a,b:~(a^b)&M),
 'min':('r',lambda a,b:min(s64(a),s64(b))&M),'max':('r',lambda a,b:max(s64(a),s64(b))&M),
 'minu':('r',lambda a,b:min(a,b)),'maxu':('r',lambda a,b:max(a,b)),
 'rol':('r',lambda a,b:rol(a,b&63,64)),'ror':('r',lambda a,b:ror(a,b&63,64)),
 'rolw':('r',lambda a,b:sx32(rol(a,b&31,32))),'rorw':('r',lambda a,b:sx32(ror(a,b&31,32))),
 'sh1add':('r',lambda a,b:((a<<1)+b)&M),'sh2add':('r',lambda a,b:((a<<2)+b)&M),'sh3add':('r',lambda a,b:((a<<3)+b)&M),
 'add.uw':('r',lambda a,b:((a&0xffffffff)+b)&M),
 'clz':('u',lambda a:clz(a,64)),'ctz':('u',lambda a:ctz(a,64)),'cpop':('u',lambda a:bin(a).count('1')),
 'clzw':('u',lambda a:clz(a,32)),'ctzw':('u',lambda a:ctz(a,32)),'cpopw':('u',lambda a:bin(a&0xffffffff).count('1')),
 'sext.b':('u',lambda a:(a&0xff)|(M^0xff if a&0x80 else 0)),'sext.h':('u',lambda a:(a&0xffff)|(M^0xffff if a&0x8000 else 0)),
 'zext.h':('u',lambda a:a&0xffff),'rev8':('u',lambda a:int.from_bytes(a.to_bytes(8,'little'),'big')),
 'orc.b':('u',lambda a:int.from_bytes(bytes(0xff if x else 0 for x in a.to_bytes(8,'little')),'little')),
}
IMMS={'rori':(lambda a,s:ror(a,s,64),[0,1,31,32,63]),'roriw':(lambda a,s:sx32(ror(a,s,32)),[0,1,16,31])}
A=[0,1,0xff,0x80,0x8000,0x7fffffff,0x80000000,0xffffffff,0x8000000000000000,M,0x0123456789abcdef,0xfedcba9876543210,0x00ff00ff00ff00ff]
B=[0,1,31,32,63,64,M,0x8000000000000000,0x0123456789abcdef]
asm=[]; exp=[]
def li(r,v): asm.append(f"  li {r}, {s64(v)}")
for n,(k,f) in OPS.items():
    if k=='r':
        for a,b in itertools.product(A,B):
            li('a1',a); li('a2',b); asm.append(f"  {n} a0, a1, a2"); asm.append("  CAPPRINT(a0)"); exp.append((n,a,b,f(a,b)&M))
    else:
        for a in A:
            li('a1',a); asm.append(f"  {n} a0, a1"); asm.append("  CAPPRINT(a0)"); exp.append((n,a,None,f(a)&M))
for n,(f,ss) in IMMS.items():
    for a in A:
        for s in ss:
            li('a1',a); asm.append(f"  {n} a0, a1, {s}"); asm.append("  CAPPRINT(a0)"); exp.append((n,a,s,f(a,s)&M))
hdr='''# zbb-arm.S (generated by gen.py): every Zbb/Zba op of the compiler lane's proposed SDK profile over edge operands,
# one CAPPRINT per result; expected.txt (same order) is computed on the host. Plain M mode.
#include "riscv_test.h"
#include "test_macros.h"
#include "asm_insn.h"
.option norvc
.section .text.init
.globl _start
_start:
  li gp, 1
'''
open('zbb-arm.S','w').write(hdr+"\n".join(asm)+"\n  RVTEST_PASS\nfail:\n  RVTEST_FAIL\n  .data\nRVTEST_DATA_BEGIN\n  TEST_DATA\nRVTEST_DATA_END\n")
open('expected.txt','w').write("".join(f"{n} {a:#x} {'' if b is None else hex(b)} {v:#x}\n" for n,a,b,v in exp))
print(len(exp),"cases")
