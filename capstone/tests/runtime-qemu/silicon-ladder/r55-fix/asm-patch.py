"""R-55 on an ARCHIVED monitor assembly (the C5u firmware's, built 2026-10-03 with an older capstone-c, so the source
cannot be regenerated byte-identically): after each of the three MMIO split_out_cap calls in cap_env_init, set the
returned capability's cursor to its MMIO base, `li t1, <base>; scc(a0, a0, t1)`, inserted right after the label that
follows the call. t1 is dead there in all three (each block reloads it within four instructions; asserted below)."""
import sys, re
p = sys.argv[1]; s = open(p).read()
if "R-55" in s:
    sys.exit("already patched")
for base in (268435456, 33603576, 33570816):            # UART 0x10000000, mtime 0x200bff8, mtimecmp 0x2004000
    m = list(re.finditer(r"  li a0, %d\n(?:  [^\n]*\n){1,12}?  call split_out_cap\n  ld ra, \d+\(sp\)\n(_cap_env_init\.\d+:\n)" % base, s))
    if len(m) != 1:
        sys.exit(f"anchor for {base:#x} matched {len(m)} times")
    at = m[0].end(1)
    nxt = s[at:at + 400].split("\n")[:6]
    t1_written = any(re.match(r"\s*(lla|li|ld|mv|add) t1,", l) for l in nxt)
    t1_read = any(re.search(r"[(, ]t1[),]", l) and not re.match(r"\s*(lla|li|ld|mv|add) t1,", l) for l in nxt[:next((i for i, l in enumerate(nxt) if re.match(r"\s*(lla|li|ld|mv|add) t1,", l)), 6)])
    if not t1_written or t1_read:
        sys.exit(f"t1 is not dead after the {base:#x} call: {nxt}")
    s = s[:at] + f"  li t1, {base}   # R-55: the carve sets its own cursor\n  scc(a0, a0, t1)\n" + s[at:]
open(p, "w").write(s); print("R-55 asm patch applied (3 sites):", p)
