#!/usr/bin/env python3
"""Emit the pointer-position table of the system calls from a Linux tree.

    gen-syscall-pointers.py LINUX [CPP] > syscall-pointers.c

For every system call that riscv64 numbers (arch/riscv/include/uapi/asm/unistd.h through
asm-generic/unistd.h, read with the C preprocessor CPP, default cpp), the table holds a mask:
bit i is set when argument i of the call's SYSCALL_DEFINE is a pointer (its type contains
'*', '__user' or a pointer typedef). Definitions come from every .c file of the tree except
the other architectures. A call defined more than once (alternatives under #ifdef) gets the
union of the masks, and the script reports each disagreement on stderr. Calls without a
SYSCALL_DEFINE (sys_ni_syscall and the like) get no entry. The binder of plan v5 step 5 adds
the positions the types miss (the mmap family, command-dependent arguments) by hand.
"""
import os
import re
import subprocess
import sys

POINTER_TYPEDEFS = {"cap_user_header_t", "cap_user_data_t", "__sighandler_t"}
# Calls with alternative definitions under #ifdef: the argument list riscv64 builds.
# RISC-V selects none of CLONE_BACKWARDS, CLONE_BACKWARDS2 and CLONE_BACKWARDS3.
RISCV_VARIANT = {"sys_clone": "clone_flags, newsp, *parent_tidptr, *child_tidptr, tls"}
DEFINE = re.compile(r"\bSYSCALL_DEFINE([0-6])\s*\(")


def numbers(linux, cpp):
    """Map sys_<name> to its riscv64 number."""
    out = subprocess.run(
        [cpp, "-P", "-nostdinc", "-D__riscv_xlen=64", "-D__SYSCALL(nr,call)=@@ nr call",
         "-I", os.path.join(linux, "arch/riscv/include/uapi"),
         "-I", os.path.join(linux, "include/uapi"),
         os.path.join(linux, "arch/riscv/include/uapi/asm/unistd.h")],
        check=True, capture_output=True, text=True).stdout
    table = {}
    for m in re.finditer(r"@@\s*\(?\s*([0-9+ ()]+?)\s*\)?\s+(sys_\w+)", out):
        table[m.group(2)] = eval(m.group(1))
    return table


def definitions(linux):
    """Yield (name, [argument types], file) for every SYSCALL_DEFINE outside other arches."""
    for root, dirs, files in os.walk(linux):
        rel = os.path.relpath(root, linux)
        parts = rel.split(os.sep)
        if parts[0] in (".git", "tools", "Documentation", "scripts", "samples"):
            dirs[:] = []
            continue
        if parts[0] == "arch" and len(parts) > 1 and parts[1] != "riscv":
            dirs[:] = []
            continue
        for f in files:
            if not f.endswith(".c"):
                continue
            path = os.path.join(root, f)
            text = open(path, errors="replace").read()
            for m in DEFINE.finditer(text):
                depth, i = 1, m.end()
                while depth and i < len(text):
                    depth += {"(": 1, ")": -1}.get(text[i], 0)
                    i += 1
                body = re.sub(r"\s+", " ", text[m.end():i - 1])
                fields = [x.strip() for x in body.split(",")]
                n = int(m.group(1))
                if len(fields) != 1 + 2 * n:
                    print(f"skip {path}: {body[:60]}", file=sys.stderr)
                    continue
                yield fields[0], fields[1::2], fields[2::2], os.path.relpath(path, linux)


def is_pointer(t):
    return "*" in t or "__user" in t or any(w in POINTER_TYPEDEFS for w in re.findall(r"\w+", t))


def main():
    linux = sys.argv[1]
    cpp = sys.argv[2] if len(sys.argv) > 2 else "cpp"
    nr = numbers(linux, cpp)
    masks, names, seen = {}, {}, {}
    for name, types, args, path in definitions(linux):
        sym = "sys_" + name
        if sym not in nr:
            continue
        mask = sum(1 << i for i, t in enumerate(types) if is_pointer(t))
        signature = ", ".join(("*" if is_pointer(t) else "") + a for t, a in zip(types, args))
        if sym in RISCV_VARIANT:
            if signature == RISCV_VARIANT[sym]:
                masks[sym], names[sym], seen[sym] = mask, signature, path
            continue
        if sym in masks and masks[sym] != mask:
            print(f"{sym}: {path} gives {mask:#x}, {seen[sym]} gave {masks[sym]:#x}", file=sys.stderr)
        masks[sym] = masks.get(sym, 0) | mask
        seen.setdefault(sym, path)
        names.setdefault(sym, signature)
    missing = [s for s in RISCV_VARIANT if s not in masks]
    if missing:
        sys.exit(f"no riscv64 variant found for {missing}")
    print("/* SPDX-License-Identifier: GPL-2.0-only */")
    print("/* Generated by capstone/kernel/tools/gen-syscall-pointers.py from the SYSCALL_DEFINE")
    print(" * types of Linux 6.1. Do not edit. Bit i of an entry: argument i is a pointer. */")
    print('#include "bind.h"')
    print()
    print("const u8 sublet_syscall_pointers[SUBLET_NR_SYSCALLS] = {")
    for sym in sorted(masks, key=lambda s: nr[s]):
        print(f"\t[{nr[sym]}] = {masks[sym]:#04x},\t/* {sym[4:]}({names[sym]}) */")
    print("};")


main()
