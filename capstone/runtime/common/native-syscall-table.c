const struct ns_descriptor *ns_descriptor_at(size_t i)
{ return i < sizeof(table) / sizeof(table[0]) ? &table[i] : NULL; }
const struct ns_descriptor *ns_descriptor(cn_u64 nr)
{
    for (size_t i = 0; i < sizeof(table) / sizeof(table[0]); ++i)
        if (table[i].nr == nr) return &table[i];
    return NULL;
}
