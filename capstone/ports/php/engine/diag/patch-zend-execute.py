#!/usr/bin/env python3
"""Emit an INSTRUMENTED copy of Zend/zend_execute.c.

Diagnostic only, and never used by a scoring build: the corpus result rests on the engine being
byte-identical, so this copy exists purely to answer which BRANCH each build takes inside
zend_assign_to_variable. CRASH-057's free (zend_execute.c:519) and its use-after-free read (:654)
each sit behind a condition, and the counters say which side of each condition this port lands on.

  usage: patch-zend-execute.py <in.c> <out.c>
"""
import sys

# (anchor, probe id, placement) -- ids 10+ record an ADDRESS instead of counting
PROBES = [
    # (unique anchor text, probe id, where to insert relative to the anchor)
    ("""			T->str_offset.str->value.str.val[T->str_offset.offset] = final_value->value.str.val[0];""",
     1, "after"),                                     # reached the string-offset tail
    ("""				if (op2->op_type == IS_VAR) {""",
     2, "after"),                                     # op2 IS_VAR
    ("""					if (value == &T(op2->u.var).tmp_var) {""",
     3, "after"),                                     # value is the temp slot
    ("""						if (result->u.EA.type & EXT_TYPE_UNUSED) {""",
     4, "after"),                                     # result unused -> STR_FREE
    ("""							/* We are going to use return value, make it real zval */""",
     5, "before"),                                    # result used -> ALLOC_ZVAL
    ("""					if (final_value == &T(op2->u.var).tmp_var) {""",
     7, "after"),                                     # THE :519 FREE -- what ASAN reports
    ("""					if (PZVAL_IS_REF(value) && value->refcount > 0) {""",
     8, "after"),                                     # THE :654 COPY -- what ASAN reports
    ("""				case IS_TMP_VAR:
					ALLOC_ZVAL(*variable_ptr_ptr);""",
     9, "after"),                                     # split path, TMP_VAR arm
    ("""				case IS_TMP_VAR:
					zendi_zval_dtor(*variable_ptr);""",
     6, "after"),                                     # NON-split path, TMP_VAR arm: struct copy
                                                      # only, so the string is never dereferenced
]

HEADER = """/* INSTRUMENTED COPY -- generated by diag/patch-zend-execute.py. Not for scoring builds. */
extern unsigned long ze_diag[];
extern unsigned long ze_addr[];
#define ZE_DIAG(n) (++ze_diag[(n)])
#define ZE_ADDR(i, p) (ze_addr[(i)] = (unsigned long)(p))
"""

def main(src, dst):
    text = open(src, encoding="utf-8", errors="surrogateescape").read()
    for anchor, pid, where in PROBES:
        n = text.count(anchor)
        if n != 1:
            sys.exit(f"anchor for probe {pid} matched {n} times, expected 1:\n{anchor[:70]}")
        if pid == 7:
            stmt = " ZE_DIAG(7); ZE_ADDR(0, final_value->value.str.val); ZE_ADDR(2, final_value);"
        elif pid == 8:
            stmt = " ZE_DIAG(8); ZE_ADDR(1, value->value.str.val); ZE_ADDR(3, value);"
        else:
            stmt = f" ZE_DIAG({pid});"
        text = text.replace(anchor, anchor + stmt if where == "after" else stmt + anchor, 1)
    # the probes sit inside functions; the declaration has to precede them
    marker = "#include "
    i = text.index(marker)
    text = text[:i] + HEADER + text[i:]
    open(dst, "w", encoding="utf-8", errors="surrogateescape").write(text)
    print(f"patched {len(PROBES)} probes into {dst}")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
