# Generate b4-t1c/stage/run.sh (PREREG Addendum 17) from run.py@69fb6cae3db4's guest SCRIPT: gen-t1b.py's substitutions
# with two changes -- the stage marker reads t1c, and the guarded insmod (a fallback; boardvm has already loaded the
# module and set both through sysfs) carries resolve_dirty=1 resolve_pte=1 -- plus a must-fire read-back after it, and, after
# the Tier 1 script's VIRTUAL_RUNTIME_DONE, the clock check and the spin pair. Every substitution is asserted.
import re, sys, hashlib
src = open(sys.argv[1]).read()
m = re.search(r"SCRIPT = r'''(.*?)'''", src, re.S); s = m.group(1)
def sub(old, new):
    global s
    assert s.count(old) == 1, old
    s = s.replace(old, new)
sub("#!/bin/sh\ncd /mnt/vm || exit 1\ninsmod capstone_vm.ko __MODULE_ARGS__ || exit 1\n",
    "#!/bin/sh\n# B check boot 3 (spec-silicon PREREG Addendum 17): run.py@69fb6cae3db4's guest SCRIPT, generated by gen-t1c.py:\n"
    "# gen-t1b.py's three substitutions (a tmpfs copy of this stage, the batch's launcher, a guarded insmod, here with\n"
    "# resolve_dirty=1 resolve_pte=1), a must-fire read-back of both, and after VIRTUAL_RUNTIME_DONE the clock check and the\n"
    "# spin pair (wait 5 s, wait 15 s), every line of which is prefixed so the Tier 1 analysis cannot count it.\n"
    "S=$(cd \"$(dirname \"$0\")\" && pwd)\nV=${SPEC_VEXEC:?set SPEC_VEXEC}\necho \"@@B4-STAGE t1c\"\n"
    "rm -rf /tmp/vm && mkdir -p /tmp/vm && cp \"$S\"/*.dom /tmp/vm/ && ln -s \"$V\" /tmp/vm/capstone-vexec && cd /tmp/vm || exit 1\n"
    "grep -q \"^capstone_vm \" /proc/modules || insmod \"$(dirname \"$V\")/capstone_vm.ko\" resolve_dirty=1 resolve_pte=1 || exit 1\n"
    "echo \"@@T1C-RD resolve_dirty=$(cat /sys/module/capstone_vm/parameters/resolve_dirty 2>/dev/null || echo ABSENT) resolve_pte=$(cat /sys/module/capstone_vm/parameters/resolve_pte 2>/dev/null || echo ABSENT)\"\n")
sub("echo VIRTUAL_RUNTIME_DONE\n",
    "cd / && rm -rf /tmp/vm\necho VIRTUAL_RUNTIME_DONE\n"
    "# --- Addendum 17, after the Tier 1 script: no line below can match a Tier 1 marker (all prefixed @@T1C-) ---\n"
    "rm -rf /tmp/vm && mkdir -p /tmp/vm && cp \"$S\"/contract.dom /tmp/vm/ && ln -s \"$V\" /tmp/vm/capstone-vexec && cd /tmp/vm || exit 1\n"
    "echo \"@@T1C-RD2 resolve_dirty=$(cat /sys/module/capstone_vm/parameters/resolve_dirty 2>/dev/null || echo ABSENT) resolve_pte=$(cat /sys/module/capstone_vm/parameters/resolve_pte 2>/dev/null || echo ABSENT)\"\n"
    "# R-52 clock check: wall time around one ok launch (date +%s%N and /proc/uptime; raw, the judge subtracts) beside\n"
    "# the launcher's own launch_ns/elapsed_ns.\n"
    "u0=$(cut -d' ' -f1 /proc/uptime); w0=$(date +%s%N 2>/dev/null)\n"
    "CAPSTONE_VM_STATS=1 ./capstone-vexec contract.dom ok argument > /tmp/clk.out 2>&1; rc=$?\n"
    "w1=$(date +%s%N 2>/dev/null); u1=$(cut -d' ' -f1 /proc/uptime)\n"
    "echo \"@@T1C-CLOCK rc=$rc w0=$w0 w1=$w1 u0=$u0 u1=$u1 $(grep '^CAPSTONE_VM_STATS ' /tmp/clk.out | grep -o 'launch_ns=[0-9]* elapsed_ns=[0-9]*')\"\n"
    "for w in 5 15; do\n"
    "  ./capstone-vexec contract.dom spin > /tmp/spin$w.out 2>&1 & spin=$!\n"
    "  sleep $w\n"
    "  kill -TERM \"$spin\" 2>/dev/null\n"
    "  wait \"$spin\"; rc=$?\n"
    "  echo \"@@T1C-SPIN wait=$w rc=$rc ready=$(grep -c '^VIRTUAL_SPIN_READY$' /tmp/spin$w.out)\"\n"
    "  sed \"s/^/@@T1C-SPIN$w-OUT /\" /tmp/spin$w.out\n"
    "done\n"
    "cd / && rm -rf /tmp/vm\n"
    "echo \"@@SPEC-DONE b4-t1c directed\"\n")
open(sys.argv[2], "w").write(s)
print("gen-t1c: run.py", hashlib.sha256(src.encode()).hexdigest()[:16], "-> run.sh", hashlib.sha256(s.encode()).hexdigest()[:16])
