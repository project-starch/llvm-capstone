#!/usr/bin/env bash
# libevent 2.1.12 for capstone64, memcached's one dependency, with its gates:
#   1. native: upstream's own test suite (make verify) passes on the host;
#   2. cross: libevent_core.a/libevent.a build with capstone-cc and the cast census on, and install;
#   3. the cross config.h is read against the native one: under --host, configure cannot run its
#      probes, so every HAVE_* that differs is listed for review;
#   4. upstream's regress links as a capstone64 domain.
# No OpenSSL, no thread support (memcached makes one NOLOCK event base per thread and never calls
# evthread_*), no samples. The epoll backend keys events by data.fd (epoll.c:198,288), which the
# runtime's 64-bit epoll_event.data carries intact.
set -euo pipefail
source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/env.sh"
source "$MC_DEPS_DIR/fetch.sh"
TAR=$(mc_fetch libevent)
N=$MC_DEPS_BUILD/libevent-native X=$MC_DEPS_BUILD/libevent-cap; LOG=$MC_DEPS_BUILD/libevent-logs
rm -rf "$N" "$X" "$LOG"; mkdir -p "$N" "$X" "$LOG"
tar -xf "$TAR" -C "$N" --strip-components=1
tar -xf "$TAR" -C "$X" --strip-components=1
OPTS=(--disable-shared --enable-static --disable-openssl --disable-thread-support --disable-samples
      --disable-debug-mode)

# Not under set -e: a failing check must reach the lines that say what failed.
set +e
( cd "$N" && env -u CC -u AR -u RANLIB ./configure "${OPTS[@]}" > "$LOG/native-configure.log" 2>&1 &&
  env -u CC -u AR -u RANLIB make -j"${JOBS:-8}" > "$LOG/native-build.log" 2>&1 &&
  env -u CC -u AR -u RANLIB make verify > "$LOG/native-check.log" 2>&1 ); nrc=$?
set -e
grep -aE 'TESTS FAILED|All tests passed' "$LOG/native-check.log" | tail -2
if [ $nrc != 0 ]; then
  # One rule for a failed test, not a judgement per run: rerun it alone, 3 times plain and 3 times
  # under EVENT_DEBUG_MODE (the variants make verify runs), and accept it only if all six pass. That
  # admits a timing test on a loaded host (util/monotonic_prc_fallback asserts two consecutive
  # monotonic reads are under 1 s apart) and refuses anything that fails again. A failed check that
  # names no test is a failure.
  mapfile -t FAILED < <(python3 - "$LOG/native-check.log" <<'PY'
import re, sys
log = open(sys.argv[1], errors='replace').read()
for full, base in sorted(set(re.findall(r'([a-z][a-z0-9_]*/[\w-]+):\s*\n\s*\[([\w-]+) FAILED\]', log))):
    if full.split('/')[-1] == base:
        print(full)
PY
)
  [ ${#FAILED[@]} -gt 0 ] || { echo "libevent: NATIVE CHECK FAILED (rc=$nrc) and no failed test could be named" >&2; exit 1; }
  for t in "${FAILED[@]}"; do
    # Tests of the components memcached never calls are reported, not gated: evdns, evhttp and evrpc.
    # build-domain.sh then proves the claim on the image: no evdns_/evhttp_/evrpc_ symbol may be in
    # memcached.dom. (dns/getaddrinfo_cancel_stress asserts that some of 1000 lookups were cancelled
    # before they completed, which a loaded host does not guarantee.)
    case "$t" in dns/*|http/*|rpc/*) echo "libevent: $t failed: out of memcached's scope (checked on the image)"; continue ;; esac
    ok=0
    for mode in "" 1; do for i in 1 2 3; do
      if ( cd "$N/test" && env ${mode:+EVENT_DEBUG_MODE=1} ./regress "$t" > "$LOG/rerun-${t//\//_}-$mode$i.log" 2>&1 ); then ok=$((ok+1)); fi
    done; done
    echo "libevent: $t failed in make verify; alone it passed $ok of 6 reruns"
    [ $ok = 6 ] || { echo "libevent: NATIVE CHECK FAILED: $t fails again" >&2; exit 1; }
  done
fi
echo "libevent: native check OK"

( cd "$X" && ./configure --host=riscv64-unknown-linux-musl --prefix="$MC_DEPS_PREFIX" "${OPTS[@]}" \
    > "$LOG/cap-configure.log" 2>&1 )
diff <(grep -E '^#define (HAVE|EVENT__HAVE)_' "$N/config.h" | sort) <(grep -E '^#define (HAVE|EVENT__HAVE)_' "$X/config.h" | sort) \
  > "$LOG/config-h.diff" || true
echo "libevent: config.h native vs cross: $(grep -c '^[<>]' "$LOG/config-h.diff") differing lines ($LOG/config-h.diff)"
# Plain make, not the library targets: include/event2/event-config.h is generated by the default
# target's BUILT_SOURCES, and a targeted make never writes it.
( cd "$X" && MC_CENSUS=1 MC_CENSUS_LOG="$LOG/cast-log.txt" make -j"${JOBS:-8}" > "$LOG/cap-build.log" 2>&1 )
( cd "$X" && make install > "$LOG/cap-install.log" 2>&1 )
touch "$LOG/cast-log.txt"; sort -u "$LOG/cast-log.txt" > "$LOG/cast-sites.txt"
echo "libevent: installed $(ls "$MC_DEPS_PREFIX/lib" | grep -c '^libevent.*\.a$') archives; cast sites: $(wc -l < "$LOG/cast-sites.txt")"
( cd "$X" && make test/regress > "$LOG/cap-test-link.log" 2>&1 )
"$CAPSTONE_LLVM_BIN/llvm-readelf" -h "$X/test/regress" > /dev/null || { echo "libevent: regress did not link" >&2; exit 1; }
echo "libevent: regress links as a domain ($(stat -c %s "$X/test/regress") bytes)"
